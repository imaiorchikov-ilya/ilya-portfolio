def выбрать_llm(провайдер):
    from crewai import LLM
    if провайдер == "ollama":
        return LLM(model="ollama/qwen3:1.7b", base_url="http://localhost:11434")
    load_dotenv_если_есть()
    return LLM(model="openai/gpt-4o-mini",
               base_url="https://api.proxyapi.ru/openai/v1",
               api_key=os.getenv("PROXYAPI_KEY") or os.getenv("OPENAI_API_KEY"))


def load_dotenv_если_есть():
    try:
        from dotenv import load_dotenv
        load_dotenv(ROOT / ".env")
    except ImportError:
        pass


def llm_call(llm, система, пользователь):
    ans = llm.call([{"role": "system", "content": система},
                    {"role": "user", "content": пользователь}])
    return str(ans).strip()


