def прогнать(url, профиль, провайдер):
    глоб = ПРОФИЛИ[профиль]
    страницы = собрать_тексты(url)
    log.info("страниц: %d", len(страницы))

    if провайдер == "нет":
        каркас = ["# КАРКАС (LLM недоступен — только детерминированная часть)",
                  f"URL: {url}, страниц снято: {len(страницы)}"]
        for u, ttl, txt in страницы:
            каркас.append(f"\n## {ttl or u}\n{txt[:700]}…")
        return "\n".join(каркас)

    llm = выбрать_llm(провайдер)
    текст = текст_для_llm(страницы)

    промпты = глоб["субпромпты"]
    if профиль == "вакансии" and РЕЗЮМЕ.exists():
        промпты += f"\nРезюме кандидата для калибровки:\n{РЕЗЮМЕ.read_text(encoding='utf-8')[:2500]}"
    ans = llm.call([{"role": "user", "content": промпты + "\n\nСАЙТ:\n" + текст}])
    m = re.search(r"\{.*\}", str(ans), re.S)
    промпты_агентов = json.loads(m.group(0))["prompts"] if m else []
    log.info("субпромптов: %d", len(промпты_агентов))

    результаты = []
    for п in промпты_агентов:
        try:
            результаты.append(llm.call([{"role": "system", "content": п},
                                        {"role": "user", "content": текст}]))
        except Exception as e:
            log.error("агент упал: %s", e)
            результаты.append(f"(агент упал: {e})")

    combined = "\n\n=== Результат анализа ===\n\n".join(str(r) for r in результаты)
    финал = llm_call(llm, ПРОФИЛИ[профиль]["финал"], combined)

    today = date.today().strftime("%d.%m.%Y")
    md = [f"# URL-агент — профиль «{профиль}»: {url} — {today}", ""]
    md.append(f"Шагов: {len(промпты_агентов)} агентов → финал. LLM: {провайдер}. Проверять руками.")
    md += ["", "## Субпромпты (агенты)", ""]
    md += [f"- {п}" for п in промпты_агентов]
    md += ["", "## Результаты агентов", ""]
    for п, р in zip(промпты_агентов, результаты):
        md += [f"### {п[:80]}…\n{р}\n"]
    md += ["", "## ФИНАЛ", "", финал]
    return "\n".join(md)


