def fetch(url):
    import requests
    log.info("GET %s", url[:100])
    r = requests.get(url, timeout=25, headers=H)
    r.raise_for_status()
    return r.text


def собрать_тексты(url, лимит=8):
    """Главная + внутренние ссылки того же домена. → [(url, title, text)]"""
    from bs4 import BeautifulSoup
    base = urllib.parse.urlparse(url)
    домен = base.netloc
    soup = strip_html(fetch(url))
    title_main = (soup.title.string or "").strip() if soup.title else ""
    страницы = [(url, title_main, soup.get_text(" ", strip=True))]

    ссылки = []
    for a in soup.find_all("a"):
        href = a.get("href") or ""
        full = urllib.parse.urljoin(url, href)
        p = urllib.parse.urlparse(full)
        if p.netloc == домен and p.path not in ("", "/") and not p.path.startswith("#"):
            if not re.search(r"\.(pdf|docx?|xlsx?|zip|jpg|png|mp4)$", p.path.lower()):
                if full not in ссылки:
                    ссылки.append(full)
    for u in ссылки[:лимит]:
        try:
            t = strip_html(fetch(u))
            ttl = (t.title.string or "").strip() if t.title else ""
            страницы.append((u, ttl, t.get_text(" ", strip=True)))
        except Exception as e:
            log.error("страница упала %s: %s", u, e)
    return страницы


def strip_html(html_text):
    from bs4 import BeautifulSoup
    return BeautifulSoup(html_text, "html.parser")


def текст_для_llm(страницы):
    return "\n---\n".join(f"{u}\n{txt[:1500]}" for u, _, txt in страницы)[:6500]


